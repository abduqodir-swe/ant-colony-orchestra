function glyphs(font, w, h, s) {
  return [...s.toUpperCase()].map((ch) => {
    const bits = (font[ch] || font[' ']).padEnd(w * h, '.');
    return bits;
  });
}

export function textWidth(s, size = 'big') {
  const w = size === 'big' ? 5 : 3;
  return s.length * (w + 1) - 1;
}

export function text(g, x, y, s, col, size = 'big', shadow) {
  const w = size === 'big' ? 5 : 3;
  const h = size === 'big' ? 7 : 5;
  const gs = glyphs(size === 'big' ? BIG : SMALL, w, h, s);
  gs.forEach((bits, i) => {
    for (let j = 0; j < w * h; j++) {
      if (bits[j] !== '#') continue;
      const px = x + i * (w + 1) + (j % w);
      const py = y + Math.floor(j / w);
      if (shadow) P(g, px, py + 1, shadow);
      P(g, px, py, col);
    }
  });
}

// Small pixel-drawing toolkit for the office: integer rects, shaded blobs, bitmap text.

export function canvas(w, h) {
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const g = c.getContext('2d');
  g.imageSmoothingEnabled = false;
  return { c, g };
}

export function R(g, x, y, w, h, col) {
  if (w <= 0 || h <= 0) return;
  g.fillStyle = col;
  g.fillRect(Math.round(x), Math.round(y), Math.round(w), Math.round(h));
}

export const P = (g, x, y, col) => R(g, x, y, 1, 1, col);

// Outlined box: 1px outline, fill, optional 1px top highlight and bottom shade.
export function box(g, x, y, w, h, fill, { outline = '#140e0c', hi, lo } = {}) {
  R(g, x, y, w, h, outline);
  R(g, x + 1, y + 1, w - 2, h - 2, fill);
  if (hi) R(g, x + 1, y + 1, w - 2, 1, hi);
  if (lo) R(g, x + 1, y + h - 2, w - 2, 1, lo);
}

export function ellipse(g, cx, cy, rx, ry, col) {
  g.fillStyle = col;
  for (let y = Math.floor(cy - ry); y <= Math.ceil(cy + ry); y++) {
    const dy = (y + 0.5 - cy) / ry;
    if (Math.abs(dy) > 1) continue;
    const half = rx * Math.sqrt(1 - dy * dy);
    const x0 = Math.round(cx - half);
    const x1 = Math.round(cx + half);
    if (x1 > x0) g.fillRect(x0, y, x1 - x0, 1);
  }
}

// Shaded blob lit from the top-left: ramp = [dark, mid, light(, highlight)].
export function blob(g, cx, cy, rx, ry, ramp, outline = '#140e0c') {
  ellipse(g, cx, cy, rx + 1, ry + 1, outline);
  for (let y = Math.floor(cy - ry); y <= Math.ceil(cy + ry); y++) {
    for (let x = Math.floor(cx - rx); x <= Math.ceil(cx + rx); x++) {
      const u = (x + 0.5 - cx) / rx;
      const v = (y + 0.5 - cy) / ry;
      const d = u * u + v * v;
      if (d > 1) continue;
      const l = -0.55 * u - 0.75 * v + 0.35 * Math.sqrt(1 - d);
      const i = l > 0.62 && ramp[3] ? 3 : l > 0.25 ? 2 : l > -0.25 ? 1 : 0;
      P(g, x, y, ramp[i]);
    }
  }
}

export function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

